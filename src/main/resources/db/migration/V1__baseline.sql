-- V1 — Schéma de référence (baseline)
--
-- Ce fichier reprend à l'identique le schéma tel qu'il était produit
-- par `spring.jpa.hibernate.ddl-auto=update` avant l'introduction de
-- Flyway. Il permet de reconstruire une base vierge de zéro.
