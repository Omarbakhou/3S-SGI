CREATE TYPE public.statut_imputation AS ENUM (
    'EN_ATTENTE',
    'VALIDEE',
    'REJETEE'
);

CREATE TABLE public.absence (
    date_debut date NOT NULL,
    date_envoi_justificatif date,
    date_fin date NOT NULL,
    nombre_jours double precision NOT NULL,
    date_demande timestamp(6) without time zone NOT NULL,
    date_validation timestamp(6) without time zone,
    id_absence bigint NOT NULL,
    id_employe bigint NOT NULL,
    id_manager_validateur bigint,
    statut character varying(20) NOT NULL,
    type_absence character varying(40) NOT NULL,
    commentaire_employe character varying(500),
    motif_rejet character varying(500),
    justificatif_url character varying(255),
    CONSTRAINT absence_statut_check CHECK (((statut)::text = ANY ((ARRAY['EN_ATTENTE'::character varying, 'VALIDEE'::character varying, 'REJETEE'::character varying, 'ANNULEE'::character varying])::text[]))),
    CONSTRAINT absence_type_absence_check CHECK (((type_absence)::text = ANY ((ARRAY['CONGE_PAYE'::character varying, 'RTT'::character varying, 'CONGE_EXCEPTIONNEL'::character varying, 'MALADIE'::character varying, 'CONGE_MATERNITE_PATERNITE'::character varying, 'SANS_SOLDE'::character varying])::text[])))
);

